package provider

import (
	"context"

	"github.com/hashicorp/terraform-plugin-sdk/v2/diag"
	"github.com/hashicorp/terraform-plugin-sdk/v2/helper/schema"
	api "goauthentik.io/api/v3"
	"goauthentik.io/terraform-provider-authentik/pkg/helpers"
)

func resourceCertificateKeyPairGenerated() *schema.Resource {
	return &schema.Resource{
		Description:   "System --- Certificate-key pair generated by authentik itself. The private key never leaves authentik, so it is not stored in the Terraform state or plan. To rotate it, change any of the arguments that force a new resource, or replace it with `-replace`/`replace_triggered_by`.",
		CreateContext: resourceCertificateKeyPairGeneratedCreate,
		ReadContext:   resourceCertificateKeyPairGeneratedRead,
		UpdateContext: resourceCertificateKeyPairGeneratedUpdate,
		DeleteContext: resourceCertificateKeyPairGeneratedDelete,
		Schema: map[string]*schema.Schema{
			"name": {
				Type:     schema.TypeString,
				Required: true,
			},
			"common_name": {
				Type:        schema.TypeString,
				Required:    true,
				ForceNew:    true,
				Description: "Common name of the certificate. authentik first names the new key pair after it, so it must not be the name of another key pair.",
			},
			"subject_alt_name": {
				Type:        schema.TypeString,
				Optional:    true,
				ForceNew:    true,
				Description: "Comma-separated DNS names.",
			},
			"validity_days": {
				Type:     schema.TypeInt,
				Optional: true,
				Default:  365,
				ForceNew: true,
			},
			"alg": {
				Type:             schema.TypeString,
				Optional:         true,
				Default:          string(api.ALGENUM_RSA),
				ForceNew:         true,
				Description:      helpers.EnumToDescription(api.AllowedAlgEnumEnumValues),
				ValidateDiagFunc: helpers.StringInEnum(api.AllowedAlgEnumEnumValues),
			},
			"certificate_data": {
				Type:        schema.TypeString,
				Computed:    true,
				Description: "PEM-encoded certificate.",
			},
			"fingerprint_sha256": {
				Type:     schema.TypeString,
				Computed: true,
			},
			"cert_expiry": {
				Type:     schema.TypeString,
				Computed: true,
			},
		},
	}
}

func resourceCertificateKeyPairGeneratedCreate(ctx context.Context, d *schema.ResourceData, m any) diag.Diagnostics {
	c := m.(*APIClient)

	req := api.CertificateGenerationRequest{
		CommonName:     d.Get("common_name").(string),
		SubjectAltName: helpers.GetP[string](d, "subject_alt_name"),
		ValidityDays:   int32(d.Get("validity_days").(int)),
		Alg:            api.AlgEnum(d.Get("alg").(string)).Ptr(),
	}
	res, hr, err := c.client.CryptoAPI.CryptoCertificatekeypairsGenerateCreate(ctx).CertificateGenerationRequest(req).Execute()
	if err != nil {
		return helpers.HTTPToDiag(d, hr, err)
	}
	d.SetId(res.Pk)

	if name := d.Get("name").(string); name != res.Name {
		_, hr, err := c.client.CryptoAPI.CryptoCertificatekeypairsPartialUpdate(ctx, res.Pk).PatchedCertificateKeyPairRequest(api.PatchedCertificateKeyPairRequest{
			Name: &name,
		}).Execute()
		if err != nil {
			// Don't leave an unnamed key pair behind.
			_, _ = c.client.CryptoAPI.CryptoCertificatekeypairsDestroy(ctx, res.Pk).Execute()
			d.SetId("")
			return helpers.HTTPToDiag(d, hr, err)
		}
	}
	return resourceCertificateKeyPairGeneratedRead(ctx, d, m)
}

func resourceCertificateKeyPairGeneratedRead(ctx context.Context, d *schema.ResourceData, m any) diag.Diagnostics {
	c := m.(*APIClient)

	res, hr, err := c.client.CryptoAPI.CryptoCertificatekeypairsRetrieve(ctx, d.Id()).Execute()
	if err != nil {
		return helpers.HTTPToDiag(d, hr, err)
	}
	helpers.SetWrapper(d, "name", res.Name)
	helpers.SetWrapper(d, "fingerprint_sha256", res.FingerprintSha256.Get())
	if exp := res.CertExpiry.Get(); exp != nil {
		helpers.SetWrapper(d, "cert_expiry", exp.String())
	}

	// Only the certificate is read back; the private key stays in authentik.
	rc, hr, err := c.client.CryptoAPI.CryptoCertificatekeypairsViewCertificateRetrieve(ctx, d.Id()).Execute()
	if err != nil {
		return helpers.HTTPToDiag(d, hr, err)
	}
	helpers.SetWrapper(d, "certificate_data", rc.Data+"\n")
	return diag.Diagnostics{}
}

func resourceCertificateKeyPairGeneratedUpdate(ctx context.Context, d *schema.ResourceData, m any) diag.Diagnostics {
	c := m.(*APIClient)

	name := d.Get("name").(string)
	_, hr, err := c.client.CryptoAPI.CryptoCertificatekeypairsPartialUpdate(ctx, d.Id()).PatchedCertificateKeyPairRequest(api.PatchedCertificateKeyPairRequest{
		Name: &name,
	}).Execute()
	if err != nil {
		return helpers.HTTPToDiag(d, hr, err)
	}
	return resourceCertificateKeyPairGeneratedRead(ctx, d, m)
}

func resourceCertificateKeyPairGeneratedDelete(ctx context.Context, d *schema.ResourceData, m any) diag.Diagnostics {
	c := m.(*APIClient)
	hr, err := c.client.CryptoAPI.CryptoCertificatekeypairsDestroy(ctx, d.Id()).Execute()
	if err != nil {
		return helpers.HTTPToDiag(d, hr, err)
	}
	return diag.Diagnostics{}
}
